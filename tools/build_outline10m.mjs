// Builds the open country's fine outline (index.html, "outline basemap"): one small file per country, the country's whole
// outline (coast and land borders) from Natural Earth 1:10m, so the line drawn round the open country follows the real coast
// rather than the 1:50m shape in country-outlines.js / world-outlines.js (thinned to 0.01 degree, about 1 km).
//   data/basemap/outline-10m/<slug>.js   window.OSAP_OUTLINE10[<Natural Earth name>] = { s: 1000, l: [lines] }
// Only the open country's file loads, after the map is up; until then (or if it fails) the 1:50m shape is drawn instead.
// Source: Natural Earth admin-0 countries (public domain) from the world-atlas npm package, thinned to 0.001 degree (~100 m).
//
//   npm install --no-save world-atlas@2.0.2 topojson-client@3     (or WORLD_ATLAS=/path/to/node_modules)
//   node tools/build_outline10m.mjs
//
// Each ring is stored as integers in 1/1000 of a degree: the first point whole, then the change from the point before.
import fs from "fs";
import path from "path";
import vm from "vm";
import { createRequire } from "module";
const require = createRequire(import.meta.url);
const base = process.env.WORLD_ATLAS ? process.env.WORLD_ATLAS.replace(/\/$/, "") + "/" : "";
const tc = require(base + "topojson-client");
const TOL = 0.001, SCALE = 1000;

function dp(pts, tol) {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const st = [[0, pts.length - 1]];
  while (st.length) {
    const [a, b] = st.pop(); let md = 0, mi = -1;
    const [x1, y1] = pts[a], [x2, y2] = pts[b], dx = x2 - x1, dy = y2 - y1, L = Math.hypot(dx, dy);
    for (let i = a + 1; i < b; i++) {
      const d = L ? Math.abs(dy * pts[i][0] - dx * pts[i][1] + x2 * y1 - y2 * x1) / L : Math.hypot(pts[i][0] - x1, pts[i][1] - y1);
      if (d > md) { md = d; mi = i; }
    }
    if (md > tol && mi > 0) { keep[mi] = 1; st.push([a, mi], [mi, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}
export const slug = (n) => n.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const root = path.join(path.dirname(new URL(import.meta.url).pathname), "..");
const out = path.join(root, "data", "basemap", "outline-10m");
// the country names the map uses (the 1:50m outline files)
const ctx = { window: {} };
for (const f of ["country-outlines.js", "world-outlines.js"]) vm.runInNewContext(fs.readFileSync(path.join(root, "data", "basemap", f), "utf8"), ctx);
const names = new Set([].concat(ctx.window.COUNTRY_BASE.features, ctx.window.WORLD_BASE.features).map((f) => f.properties.n));
const topo = require(base + "world-atlas/countries-10m.json");
const fc = tc.feature(topo, topo.objects.countries);
fs.rmSync(out, { recursive: true, force: true }); fs.mkdirSync(out, { recursive: true });
let n = 0, bytes = 0; const miss = [];
for (const name of [...names].sort()) {
  const fs10 = fc.features.filter((f) => f.properties.name === name);
  if (!fs10.length) { miss.push(name); continue; }
  const lines = [];
  for (const f of fs10) {
    const g = f.geometry, polys = g.type === "Polygon" ? [g.coordinates] : g.coordinates;
    for (const poly of polys) for (const ring of poly) {
      const r = dp(ring, TOL).map(([x, y]) => [Math.round(x * SCALE), Math.round(y * SCALE)]);
      if (r.length < 3) continue;
      const enc = [r[0][0], r[0][1]];
      for (let i = 1; i < r.length; i++) { const dx = r[i][0] - r[i - 1][0], dy = r[i][1] - r[i - 1][1]; if (dx || dy) enc.push(dx, dy); }
      lines.push(enc);
    }
  }
  const js = "/* generated by tools/build_outline10m.mjs from Natural Earth 1:10m admin-0 countries (public domain); do not edit by hand */\n" +
    "(window.OSAP_OUTLINE10=window.OSAP_OUTLINE10||{})[" + JSON.stringify(name) + "]=" + JSON.stringify({ s: SCALE, l: lines }) + ";\n";
  fs.writeFileSync(path.join(out, slug(name) + ".js"), js); n++; bytes += js.length;
}
console.log(n + " countries, " + Math.round(bytes / 1024) + " KB in all" + (miss.length ? "; no 1:10m shape for: " + miss.join(", ") : ""));
