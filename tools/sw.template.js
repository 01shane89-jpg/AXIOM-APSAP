/* ASAP service worker: makes the app installable and usable offline.
   Generated by tools/split_page.py; __VERSION__ and __PRECACHE__ are filled in there.
   - App shell and packaged data: cached on install, served cache-first, replaced when VERSION changes.
   - index.html and the feed files: network-first, so a connected device always sees the newest published
     data and an offline one falls back to the last copy it saw. Feed files wait at most DATA_WAIT for the network.
   - Live feeds (ThaiWater, GISTDA) are never cached here; the page handles their failure itself.
   - Map tiles from other hosts: cached as they are viewed, capped at MAX_TILES entries. */
const VERSION = "__VERSION__";
const SHELL = "asap-shell-" + VERSION, TILES = "asap-tiles", MAX_TILES = 1500;
const DATA_WAIT = 4000;
const PRECACHE = __PRECACHE__;
const FRESH = [/\/index\.html$/, /\/$/, /data\/thailand\/flood-live-snapshot\.js$/, /data\/live\/[a-z-]+\.js$/, /data\/history\/[a-z]+\.js$/];
const NEVER = [/thaiwater\.net/, /gistda\.or\.th/, /open-meteo\.com/, /gibs\.earthdata\.nasa\.gov/];

self.addEventListener("install", (e) => {
  // cache: "reload" skips the browser's HTTP cache (GitHub Pages lets it keep files for 10 minutes),
  // so a new version never stores the previous deploy's files.
  e.waitUntil(caches.open(SHELL).then((c) => c.addAll(PRECACHE.map((u) => new Request(u, { cache: "reload" })))).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith("asap-shell-") && k !== SHELL).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});
async function trim(name, max) {
  const c = await caches.open(name), ks = await c.keys();
  for (let i = 0; i < ks.length - max; i++) await c.delete(ks[i]);
}
self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (NEVER.some((r) => r.test(url.href))) return;
  if (url.origin === location.origin && FRESH.some((r) => r.test(url.pathname))) {
    // "no-cache" asks the server every time (a cheap check when nothing changed), so a new deploy shows on the next load.
    const net = fetch(req.url, { cache: "no-cache", credentials: "same-origin" }).then((res) => {
      if (res.ok) { const copy = res.clone(); caches.open(SHELL).then((c) => c.put(req, copy)); }
      return res;
    });
    const fallback = () => caches.match(req, { ignoreSearch: true }).then((r) => r || caches.match("./index.html"));
    if (/\/data\//.test(url.pathname)) {
      // Feed files: on a slow connection, wait at most DATA_WAIT ms, then use the last saved copy so the page still opens;
      // the network copy keeps downloading and is saved for the next open (or the Refresh button).
      e.respondWith(Promise.race([net.catch(() => null), new Promise((r) => setTimeout(() => r(null), DATA_WAIT))])
        .then((res) => res || caches.match(req, { ignoreSearch: true }).then((r) => r || net)).catch(fallback));
      return;
    }
    e.respondWith(net.catch(fallback));
    return;
  }
  e.respondWith(caches.match(req, { ignoreSearch: url.origin === location.origin }).then((hit) => hit || fetch(req).then((res) => {
    if (res.ok || res.type === "opaque") {
      const copy = res.clone(), name = url.origin === location.origin ? SHELL : TILES;
      caches.open(name).then((c) => c.put(req, copy)).then(() => { if (name === TILES) trim(TILES, MAX_TILES); });
    }
    return res;
  })));
});
// Watch notifications (shown by the page): a tap focuses an open OSAP window on the hit, or opens one.
self.addEventListener("notificationclick", (e) => {
  e.notification.close();
  const url = new URL((e.notification.data && e.notification.data.url) || "./", self.registration.scope).href;
  e.waitUntil(self.clients.matchAll({ type: "window", includeUncontrolled: true }).then((cs) => {
    const c = cs.find((x) => x.url.startsWith(self.registration.scope) && !/[?&]watchscan=1/.test(x.url));
    if (c) return c.focus().then((w) => (w && w.navigate ? w.navigate(url) : null)).catch(() => self.clients.openWindow(url));
    return self.clients.openWindow(url);
  }));
});
