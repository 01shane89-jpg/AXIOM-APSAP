// Builds the open country's territorial sea line (index.html, "outline basemap"): the outer limit of each country's 12 nautical
// mile territorial sea, one small file per country, drawn as a very fine dashed line beside the country's own outline.
//   data/basemap/ts12/<iso3>.js   window.OSAP_TS12[<ISO3>] = { s: 1000, l: [12 nm limits], d: [overlapping claims / joint regimes] }
// Only the open country's file loads, after the map is up. A country with no file (landlocked) simply has none.
// Source: Marine Regions "Maritime Boundaries" territorial seas (12 NM) layer, Flanders Marine Institute (VLIZ), fetched from its
// public WFS (no key, no account). Licence: CC BY 4.0 per marineregions.org/disclaimer.php; kept in a folder of its own so it can be
// stripped. Only each polygon's outer ring is kept (the 12 nm limit and the lateral lines to neighbours); its holes are the
// baselines and islands, which the country outline already draws. Thinned to 0.002 degree (~200 m).
//
//   node tools/build_ts12.mjs                (fetches the layer; GitHub Actions: .github/workflows/build-ts12.yml)
//   node tools/build_ts12.mjs saved.geojson  (from a saved GetFeature response)
//
// Each ring is stored as integers in 1/1000 of a degree: the first point whole, then the change from the point before.
import fs from "fs";
import path from "path";
const TOL = 0.002, SCALE = 1000;
const WFS = "https://geo.vliz.be/geoserver/MarineRegions/wfs?service=WFS&version=1.0.0&request=GetFeature" +
  "&typeName=MarineRegions:eez_12nm&outputFormat=application/json&srsName=EPSG:4326";

function dp(pts, tol) {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const st = [[0, pts.length - 1]];
  while (st.length) {
    const [a, b] = st.pop(); let md = 0, mi = -1;
    const [x1, y1] = pts[a], [x2, y2] = pts[b], dx = x2 - x1, dy = y2 - y1, L = Math.hypot(dx, dy);
    for (let i = a + 1; i < b; i++) {
      const d = L ? Math.abs(dy * pts[i][0] - dx * pts[i][1] + x2 * y1 - y2 * x1) / L : Math.hypot(pts[i][0] - x1, pts[i][1] - y1);
      if (d > md) { md = d; mi = i; }
    }
    if (md > tol && mi > 0) { keep[mi] = 1; st.push([a, mi], [mi, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}
function enc(ring) {
  const r = dp(ring, TOL).map(([x, y]) => [Math.round(x * SCALE), Math.round(y * SCALE)]);
  if (r.length < 3) return null;
  const e = [r[0][0], r[0][1]];
  for (let i = 1; i < r.length; i++) { const dx = r[i][0] - r[i - 1][0], dy = r[i][1] - r[i - 1][1]; if (dx || dy) e.push(dx, dy); }
  return e;
}
let gj;
if (process.argv[2]) gj = JSON.parse(fs.readFileSync(process.argv[2], "utf8"));
else {
  const res = await fetch(WFS, { headers: { "User-Agent": "AXIOM-OSAP build (github.com/01shane89-jpg/AXIOM-APSAP)" }, signal: AbortSignal.timeout(600000) });
  if (!res.ok) throw new Error("Marine Regions WFS answered " + res.status);
  gj = await res.json();
}
const feats = gj.features || [];
if (feats.length < 100) throw new Error("only " + feats.length + " territorial sea shapes came back; not overwriting");
const by = {}, kinds = {};
for (const f of feats) {
  const p = {}; for (const k in f.properties || {}) p[k.toLowerCase()] = f.properties[k];
  const kind = String(p.pol_type || ""); kinds[kind] = (kinds[kind] || 0) + 1;
  const shared = /overlap|joint/i.test(kind);
  const isos = [p.iso_ter1, p.iso_ter2, p.iso_ter3].filter((x) => x && /^[A-Z]{3}$/.test(x));
  if (!f.geometry || !isos.length) continue;
  const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.type === "MultiPolygon" ? f.geometry.coordinates : [];
  const rings = polys.map((poly) => enc(poly[0])).filter(Boolean);
  for (const iso of new Set(isos)) { const o = by[iso] = by[iso] || { l: [], d: [] }; (shared ? o.d : o.l).push(...rings); }
}
const root = path.join(path.dirname(new URL(import.meta.url).pathname), "..");
const out = path.join(root, "data", "basemap", "ts12");
fs.rmSync(out, { recursive: true, force: true }); fs.mkdirSync(out, { recursive: true });
let bytes = 0;
for (const iso of Object.keys(by).sort()) {
  const js = "/* generated by tools/build_ts12.mjs from Marine Regions territorial seas (12 NM), VLIZ, CC BY 4.0; do not edit by hand */\n" +
    "(window.OSAP_TS12=window.OSAP_TS12||{})[" + JSON.stringify(iso) + "]=" + JSON.stringify({ s: SCALE, l: by[iso].l, d: by[iso].d }) + ";\n";
  fs.writeFileSync(path.join(out, iso.toLowerCase() + ".js"), js); bytes += js.length;
}
console.log(feats.length + " shapes (" + JSON.stringify(kinds) + "); " + Object.keys(by).length + " countries, " + Math.round(bytes / 1024) + " KB in all");
